import { SEVERITIES } from "../severity.js";

export function formatMarkdown(result) {
  const lines = [];
  lines.push("# CSC Architecture Review");
  lines.push("");
  lines.push("## Verdict");
  lines.push(result.verdict);
  lines.push("");
  lines.push("## Summary");
  lines.push(result.summary);
  lines.push("");
  lines.push("## Findings");

  const grouped = groupBySeverity(result.findings);
  let hadAny = false;
  for (const severity of SEVERITIES) {
    const items = grouped.get(severity) || [];
    if (items.length === 0) continue;
    hadAny = true;
    lines.push("");
    lines.push(`### ${severity}`);
    for (const f of items) {
      lines.push(`- **[${shortCategory(f.category)}] ${f.title}** _(\`${f.rule_id}\`)_`);
      if (f.file) {
        lines.push(`  - File: \`${f.file}${f.line ? `:${f.line}` : ""}\``);
      }
      lines.push(`  - Why it matters: ${f.why_it_matters}`);
      lines.push(`  - Recommendation: ${f.recommendation}`);
      if (f.suggested_fix) lines.push(`  - Suggested fix: ${f.suggested_fix}`);
    }
  }
  if (!hadAny) {
    lines.push("");
    lines.push("_No findings._");
  }

  lines.push("");
  lines.push("## Architecture Fit");
  lines.push(result.architecture_fit.fits_platform ? "Fits the CSC platform model." : "Does **not** cleanly fit the CSC platform model.");
  for (const note of result.architecture_fit.notes) lines.push(`- ${note}`);

  lines.push("");
  lines.push("## Linear / GitHub Checks");
  const L = result.linear;
  lines.push(`- Linear issue detected: ${L.issue_detected ? "yes" : "no"}`);
  lines.push(`- Issue key: ${L.issue_key || "—"}`);
  lines.push(`- PR title references issue: ${yesNo(L.references_in_pr_title)}`);
  lines.push(`- Branch name references issue: ${yesNo(L.references_in_branch)}`);
  lines.push(`- Commit message references issue: ${yesNo(L.references_in_commits)}`);

  lines.push("");
  lines.push("## GCP Deployment Notes");
  const gcpFindings = result.findings.filter((f) =>
    ["Cloud Run/deployment", "GCS/document storage", "IAM/service accounts", "Firebase/Auth/Firestore rules", "Secrets/configuration"].includes(f.category)
  );
  if (gcpFindings.length === 0) {
    lines.push("No GCP-facing concerns flagged in this PR.");
  } else {
    for (const f of gcpFindings) {
      lines.push(`- **${f.severity}** [${shortCategory(f.category)}] ${f.title}${f.file ? ` (\`${f.file}\`)` : ""}`);
    }
  }

  if (result.blast_radius && result.blast_radius.length > 0) {
    lines.push("");
    lines.push("## Blast Radius");
    for (const module of result.blast_radius) lines.push(`- ${module}`);
  }

  lines.push("");
  lines.push("## Final Recommendation");
  lines.push(finalRecommendation(result));
  lines.push("");
  lines.push(`_Generated by csc-architecture-reviewer • rules: ${result.meta.rules_run.length} • files: ${result.meta.changed_files}_`);

  return lines.join("\n") + "\n";
}

function groupBySeverity(findings) {
  const map = new Map();
  for (const f of findings) {
    const list = map.get(f.severity) || [];
    list.push(f);
    map.set(f.severity, list);
  }
  return map;
}

function yesNo(v) {
  return v ? "yes" : "no";
}

function shortCategory(category) {
  const map = {
    "Security": "SECURITY",
    "GCP architecture": "GCP",
    "Firebase/Auth/Firestore rules": "FIRESTORE",
    "Cloud Run/deployment": "RUN",
    "GCS/document storage": "GCS",
    "Secrets/configuration": "CONFIG",
    "IAM/service accounts": "IAM",
    "Data model/shared collections": "DATA",
    "Frontend/backend boundary": "BOUNDARY",
    "Linear/GitHub process compliance": "PROCESS",
    "Observability/logging/audit trail": "AUDIT",
    "Platform consistency": "PLATFORM",
  };
  return map[category] || category;
}

function finalRecommendation(result) {
  if (result.verdict === "FAIL") {
    return "Block merge. Address all BLOCKER findings, then re-run the reviewer.";
  }
  if (result.verdict === "PASS_WITH_WARNINGS") {
    return "Safe to merge after the reviewer's HIGH/MEDIUM findings are either fixed or explicitly acknowledged with `csc-reviewer-disable-next-line <RULE> -- <reason>`.";
  }
  return "No reviewer concerns. Merge when ready.";
}
